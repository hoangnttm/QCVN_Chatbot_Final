"""Minimal access control until M9 (real auth): a shared admin token and an anonymous client id.

- Admin routes: header `X-Admin-Token` must equal `Settings.admin_token` (constant-time compare).
  Replacing this dependency with a session/JWT check is the whole of M9 for the API side.
- Public routes: an optional `X-Client-Id` (UUID generated by the browser) identifies a client for
  history and daily usage; without it the caller is keyed by IP.
"""

from __future__ import annotations

import hmac
import uuid

from fastapi import HTTPException, Request, Security
from fastapi.security import APIKeyHeader

from app.core.config import get_settings

# declared as a security scheme so Swagger (/docs) shows "Authorize" for the admin routes
ADMIN_TOKEN_HEADER = APIKeyHeader(
    name="X-Admin-Token", auto_error=False, description="ADMIN_TOKEN (backend/.env)"
)


def require_admin(given: str | None = Security(ADMIN_TOKEN_HEADER)) -> None:
    token = get_settings().admin_token
    if not token:
        raise HTTPException(503, "ADMIN_TOKEN chưa được cấu hình trên máy chủ")
    given = given or ""
    if not hmac.compare_digest(given.encode(), token.encode()):
        raise HTTPException(401, "Thiếu hoặc sai X-Admin-Token")


def get_client_id(request: Request) -> str | None:
    """The browser-generated UUID, normalised; None when absent or malformed."""
    raw = (request.headers.get("x-client-id") or "").strip()
    if not raw:
        return None
    try:
        return str(uuid.UUID(raw))
    except ValueError:
        return None


def get_client_key(request: Request) -> str:
    """Key for daily usage: `cid:<uuid>` when the browser sent one, else `ip:<host>`."""
    cid = get_client_id(request)
    if cid:
        return f"cid:{cid}"
    host = request.client.host if request.client else "unknown"
    return f"ip:{host}"
